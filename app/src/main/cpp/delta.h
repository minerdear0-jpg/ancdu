#pragma once
#include "arena.h"

/* «Что выросло»: Δ нового дерева против базы — прошлого скана того же корня (кэш-файл).
 * Только чтение обоих деревьев; ничего не удаляет и не пишет на диск. */

/* Состояние узла нового дерева (st[]). */
enum {
  DELTA_SAME = 0, /* был в базе: Δ = новый размер − старый */
  DELTA_NEW = 1,  /* не было в базе (или был другого вида — файл ↔ каталог): Δ = свой размер */
  DELTA_DEAD = 2, /* удалён (F_DELETED) или под удалённым: Δ = 0, не показывается */
};

/* Каталог нового дерева, у которого в базе были дети, не найденные теперь («ушло»). */
typedef struct {
  uint32_t node;           /* каталог нового дерева */
  uint32_t count;          /* сколько его прямых детей базы не нашлось */
  uint64_t disk, apparent; /* сумма их размеров в базе (итоги поддеревьев) */
} delta_gone;

/*
 * Узлы сопоставляются по пути имён от корня (байты, файл с файлом, каталог с каталогом): обход
 * нового дерева сверху вниз, у каждой сопоставленной пары каталогов — хеш детей базы по имени
 * (одна таблица, растёт до самого широкого каталога). O(n + m) в среднем.
 * d_disk, d_app, st — по count(cur) элементов (пишет функция). *gone — malloc (free — вызывающий),
 * по возрастанию node, только count > 0; *gone_n — их число. Удалённое в базе (F_DELETED) не
 * считается бывшим. 0; -EINVAL — base без корня или не ST_DONE/ST_FULL; -EXDEV — другой корень
 * (root_path); -ENOMEM. При ошибке *gone = NULL, *gone_n = 0.
 */
int delta_compute(const arena *cur, const arena *base, int64_t *d_disk, int64_t *d_app,
                  uint8_t *st, delta_gone **gone, uint32_t *gone_n);

/* То же против файла базы: arena_open_file (mmap, та же проверка, что у кэша) и unmap.
 * -ENOEXEC — файл ancdu другой версии формата (его молча забывают, как кэш), -EINVAL — негоден,
 * -ENOENT и прочие — из open. */
int delta_compute_file(const arena *cur, const char *base_path, int64_t *d_disk, int64_t *d_app,
                       uint8_t *st, delta_gone **gone, uint32_t *gone_n);
